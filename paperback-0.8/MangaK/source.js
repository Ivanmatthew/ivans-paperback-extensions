    // When a search involves inverse patterns (e.g. !Syrup), the aggregation
    // across keys switches from "ANY key matches" to "ALL keys must match."
    // This is signaled by hasInverse on the SearchResult from ExtendedSearch.
    //
    // For mixed patterns like "^hello !Syrup", a key failure is ambiguous —
    // it could be the positive or inverse term that failed. In that case we
    // conservatively exclude the item, which is strictly better than the old
    // behavior of including it. See: https://github.com/krisk/Fuse/issues/712
    _searchObjectList(query, {
      heap,
      ignoreFieldNorm
    } = {}) {
      const searcher = this._getSearcher(query);
      const {
        keys,
        records
      } = this._myIndex;
      const results = heap ? null : [];
      records.forEach(({
        $: item,
        i: idx
      }) => {
        if (!isDefined(item)) {
          return;
        }
        const matches = [];
        let anyKeyFailed = false;
        let hasInverse = false;
        keys.forEach((key, keyIndex) => {
          const keyMatches = this._findMatches({
            key,
            value: item[keyIndex],
            searcher
          });
          if (keyMatches.length) {
            matches.push(...keyMatches);
            if (keyMatches[0].hasInverse) {
              hasInverse = true;
            }
          } else {
            anyKeyFailed = true;
          }
        });
        if (hasInverse && anyKeyFailed) {
          return;
        }
        if (matches.length) {
          const result = {
            idx,
            item,
            matches
          };
          if (heap) {
            result.score = computeScoreSingle(result.matches, {
              ignoreFieldNorm
            });
            if (heap.shouldInsert(result.score)) {
              heap.insert(result);
            }
          } else {
            results.push(result);
          }
        }
      });
      return results;
    }
    _findMatches({
      key,
      value,
      searcher
    }) {
      if (!isDefined(value)) {
        return [];
      }
      const matches = [];
      if (isArray(value)) {
        value.forEach(({
          v: text,
          i: idx,
          n: norm2
        }) => {
          if (!isDefined(text)) {
            return;
          }
          const {
            isMatch,
            score,
            indices,
            hasInverse
          } = searcher.searchIn(text);
          if (isMatch) {
            matches.push({
              score,
              key,
              value: text,
              idx,
              norm: norm2,
              indices,
              hasInverse
            });
          }
        });
      } else {
        const {
          v: text,
          n: norm2
        } = value;
        const {
          isMatch,
          score,
          indices,
          hasInverse
        } = searcher.searchIn(text);
        if (isMatch) {
          matches.push({
            score,
            key,
            value: text,
            norm: norm2,
            indices,
            hasInverse
          });
        }
      }
      return matches;
    }
